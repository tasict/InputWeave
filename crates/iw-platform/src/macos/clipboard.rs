/// Types that mark content as not to be shared, from nspasteboard.org.
/// Password managers put them on what they copy.
const PRIVATE_TYPES: [&str; 2] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
];

/// Types that tell clipboard managers, by nspasteboard.org's convention,
/// not to record content or show it in their history: put on promises of
/// files, so that a manager does not read their file URLs, which would
/// fetch the files. It also has them left alone here, as `PRIVATE_TYPES`
/// has the transient one; the agent never reads its own promise again.
const UNRECORDED_TYPES: [&str; 2] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

/// Promises whose providers are kept alive at most; beyond, the oldest
/// go, finished or not.
const PROVIDERS: usize = 16;

/// The general pasteboard, or a named one for tests.
pub struct MacClipboard {
    pasteboard: Retained<NSPasteboard>,
    /// What answers for content promised, one per pasteboard item and a
    /// group per promise, kept until AppKit says it is finished with each
    /// of a group (`pasteboardFinishedWithDataProvider:`) and then
    /// released at the next write, never while AppKit may still message
    /// one. AppKit's NSPasteboardItem.h does not say whether an item
    /// retains its data provider, so nothing relies on it.
    providers: Vec<Vec<Retained<Provider>>>,
}

// SAFETY: NSPasteboard talks to the pasteboard server and may be used from
// any thread; the agent uses it from one at a time.
unsafe impl Send for MacClipboard {}

impl MacClipboard {
    pub fn general() -> Self {
        Self {
            pasteboard: NSPasteboard::generalPasteboard(),
            providers: Vec::new(),
        }
    }

    /// A private pasteboard, so tests never touch the user's clipboard.
    pub fn named(name: &str) -> Self {
        Self {
            pasteboard: NSPasteboard::pasteboardWithName(&NSString::from_str(name)),
            providers: Vec::new(),
        }
    }

    fn pasteboard_type(format: ClipboardFormat) -> &'static NSPasteboardType {
        // SAFETY: reading immutable framework constants.
        unsafe {
            match format {
                ClipboardFormat::Text => NSPasteboardTypeString,
                ClipboardFormat::Rtf => NSPasteboardTypeRTF,
                ClipboardFormat::Html => NSPasteboardTypeHTML,
                ClipboardFormat::Png => NSPasteboardTypePNG,
            }
        }
    }

    /// PNG for an image the pasteboard only has as TIFF, as many apps
    /// copy them.
    fn png_from_tiff(&self) -> Option<Vec<u8>> {
        // SAFETY: reading an immutable framework constant.
        let tiff = self
            .pasteboard
            .dataForType(unsafe { NSPasteboardTypeTIFF })?;
        let image = NSBitmapImageRep::imageRepWithData(&tiff)?;
        // SAFETY: an empty dictionary is a valid set of properties.
        let png = unsafe {
            image.representationUsingType_properties(
                NSBitmapImageFileType::PNG,
                &NSDictionary::new(),
            )
        }?;
        Some(png.to_vec())
    }
}

impl Clipboard for MacClipboard {
    fn change_count(&self) -> Result<u64, PlatformError> {
        Ok(self.pasteboard.changeCount() as u64)
    }

    fn read(&self, max_len: usize) -> Result<ClipboardRead, PlatformError> {
        let Some(types) = self.pasteboard.types() else {
            return Ok(ClipboardRead::Empty);
        };
        if Self::private(&types) {
            return Ok(ClipboardRead::Sensitive);
        }
        let mut content = ClipboardContent::default();
        for format in ClipboardFormat::ALL {
            let data = match self.pasteboard.dataForType(Self::pasteboard_type(format)) {
                Some(data) => Some(data.to_vec()),
                None if format == ClipboardFormat::Png => self.png_from_tiff(),
                None => None,
            };
            if let Some(data) = data.filter(|d| !d.is_empty()) {
                content.items.push((format, data));
            }
            if content.len() > max_len {
                return Ok(ClipboardRead::TooLarge(content.len()));
            }
        }
        Ok(if content.is_empty() {
            ClipboardRead::Empty
        } else {
            ClipboardRead::Content(content)
        })
    }

    fn write(&mut self, content: &ClipboardContent) -> Result<u64, PlatformError> {
        self.pasteboard.clearContents();
        self.release_finished();
        for (format, data) in &content.items {
            let data = NSData::with_bytes(data);
            if !self
                .pasteboard
                .setData_forType(Some(&data), Self::pasteboard_type(*format))
            {
                return Err(PlatformError::Os(format!(
                    "cannot put {} on the pasteboard",
                    format.mime()
                )));
            }
        }
        Ok(self.pasteboard.changeCount() as u64)
    }

    /// The file URLs on the pasteboard, as Finder copies files: the path
    /// of each item's `public.file-url`, file reference URLs resolved.
    /// Nothing when the pasteboard is marked not to be shared.
    fn files(&self) -> Result<Vec<PathBuf>, PlatformError> {
        if self.pasteboard.types().is_some_and(|t| Self::private(&t)) {
            return Ok(Vec::new());
        }
        let Some(items) = self.pasteboard.pasteboardItems() else {
            return Ok(Vec::new());
        };
        // SAFETY: reading an immutable framework constant.
        let file_url = unsafe { NSPasteboardTypeFileURL };
        let paths = items
            .iter()
            .filter_map(|item| item.stringForType(file_url))
            .filter_map(|url| NSURL::URLWithString(&url))
            .filter_map(|url| url.filePathURL())
            .filter(|url| url.isFileURL())
            .filter_map(|url| url.path())
            .map(|path| PathBuf::from(path.to_string()))
            .collect();
        Ok(paths)
    }

    fn promises_files(&self) -> bool {
        true
    }

    /// A pasteboard item for each file promised, whose `public.file-url`
    /// `Provider` hands out once the files arrived (Finder pastes file
    /// URLs, not file promises), the formats and `UNRECORDED_TYPES` on
    /// the first; or one item for the formats alone. AppKit asks through
    /// the main thread's run loop, which the agent runs for it
    /// (`run_beside_main_loop`); the declaring thread does not matter.
    fn write_promise(&mut self, promise: ClipboardPromise) -> Result<u64, PlatformError> {
        let count = promise.files.len().max(1);
        // The promise is finished once AppKit is with every item's.
        let left = Arc::new(AtomicUsize::new(count));
        let mut group = Vec::with_capacity(count);
        let mut items = Vec::with_capacity(count);
        for index in 0..count {
            let file = (index < promise.files.len()).then_some(index);
            let mut types: Vec<&NSPasteboardType> = Vec::new();
            if index == 0 {
                types.extend(promise.formats.iter().map(|f| Self::pasteboard_type(*f)));
            }
            if file.is_some() {
                // SAFETY: reading an immutable framework constant.
                types.push(unsafe { NSPasteboardTypeFileURL });
            }
            let provider = Provider::new(promise.source.clone(), file, left.clone());
            let item = NSPasteboardItem::new();
            if !item.setDataProvider_forTypes(
                ProtocolObject::from_ref(&*provider),
                &NSArray::from_slice(&types),
            ) {
                return Err(PlatformError::Os(
                    "cannot promise content on the pasteboard".to_owned(),
                ));
            }
            if index == 0 && !promise.files.is_empty() {
                let empty = NSData::new();
                for marker in UNRECORDED_TYPES {
                    if !item.setData_forType(&empty, &NSString::from_str(marker)) {
                        return Err(PlatformError::Os(
                            "cannot mark promised files on the pasteboard".to_owned(),
                        ));
                    }
                }
            }
            items.push(ProtocolObject::from_retained(item));
            group.push(provider);
        }
        self.pasteboard.clearContents();
        if !self
            .pasteboard
            .writeObjects(&NSArray::from_retained_slice(&items))
        {
            return Err(PlatformError::Os(
                "cannot promise content on the pasteboard".to_owned(),
            ));
        }
        self.release_finished();
        self.providers.push(group);
        Ok(self.pasteboard.changeCount() as u64)
    }
}

impl MacClipboard {
    /// Whether `types` mark the pasteboard as not to be shared.
    fn private(types: &NSArray<NSPasteboardType>) -> bool {
        types
            .iter()
            .any(|t| PRIVATE_TYPES.contains(&t.to_string().as_str()))
    }

    /// Lets go of the promises AppKit is finished with, and of the oldest
    /// beyond a few, which AppKit never said it was finished with.
    fn release_finished(&mut self) {
        self.providers.retain(|group| {
            group
                .iter()
                .any(|p| !p.ivars().finished.load(Ordering::SeqCst))
        });
        let extra = self.providers.len().saturating_sub(PROVIDERS - 1);
        if extra > 0 {
            tracing::warn!(
                extra,
                "letting go of pasteboard providers AppKit never finished with"
            );
            self.providers.drain(..extra);
        }
    }

    /// Providers kept alive now, for tests.
    pub fn providers_kept(&self) -> usize {
        self.providers.iter().map(Vec::len).sum()
    }
}

struct ProviderIvars {
    source: Arc<dyn ClipboardSource>,
    /// The promised file whose URL its item has, by place.
    file: Option<usize>,
    /// The providers of the promise AppKit is not finished with yet.
    left: Arc<AtomicUsize>,
    /// AppKit is finished with it, so it may be released.
    finished: AtomicBool,
}

define_class!(
    // SAFETY: NSObject has no subclassing requirements, and Provider does
    // not implement Drop.
    #[unsafe(super(NSObject))]
    #[name = "InputWeaveClipboardProvider"]
    #[ivars = ProviderIvars]
    struct Provider;

    unsafe impl NSObjectProtocol for Provider {}

    unsafe impl NSPasteboardItemDataProvider for Provider {
        #[unsafe(method(pasteboard:item:provideDataForType:))]
        fn provide_data_for_type(
            &self,
            _pasteboard: Option<&NSPasteboard>,
            item: &NSPasteboardItem,
            r#type: &NSPasteboardType,
        ) {
            self.provide(item, r#type);
        }

        #[unsafe(method(pasteboardFinishedWithDataProvider:))]
        fn finished_with_data_provider(&self, _pasteboard: &NSPasteboard) {
            let ivars = self.ivars();
            if !ivars.finished.swap(true, Ordering::SeqCst)
                && ivars.left.fetch_sub(1, Ordering::SeqCst) == 1
            {
                ivars.source.finished();
            }
        }
    }
);

impl Provider {
    fn new(
        source: Arc<dyn ClipboardSource>,
        file: Option<usize>,
        left: Arc<AtomicUsize>,
    ) -> Retained<Self> {
        let this = Self::alloc().set_ivars(ProviderIvars {
            source,
            file,
            left,
            finished: AtomicBool::new(false),
        });
        // SAFETY: NSObject's designated initializer.
        unsafe { msg_send![super(this), init] }
    }

    /// Puts the bytes of `r#type` on `item`. The first time this blocks
    /// the main thread until the content arrives, for at most
    /// `PROMISE_WAIT`; the source keeps it for the other formats, and
    /// remembers a failure. Nothing is put there when it cannot be had.
    fn provide(&self, item: &NSPasteboardItem, r#type: &NSPasteboardType) {
        // SAFETY: reading an immutable framework constant.
        if r#type.isEqualToString(unsafe { NSPasteboardTypeFileURL }) {
            self.provide_file(item, r#type);
            return;
        }
        let Some(format) = ClipboardFormat::ALL
            .into_iter()
            .find(|f| MacClipboard::pasteboard_type(*f).isEqualToString(r#type))
        else {
            return;
        };
        if let Some(bytes) = self.ivars().source.fetch(format) {
            item.setData_forType(&NSData::with_bytes(&bytes), r#type);
        }
    }

    /// Puts the URL of the promised file on `item`, once the files arrived
    /// in a folder of the agent's: the first time this blocks the main
    /// thread for them, at most `PROMISE_WAIT`; past that nothing, and a
    /// later paste gets it while they keep coming.
    fn provide_file(&self, item: &NSPasteboardItem, r#type: &NSPasteboardType) {
        let Some(index) = self.ivars().file else {
            return;
        };
        let FilesFetch::Ready(paths) = self.ivars().source.fetch_files() else {
            return;
        };
        let Some(path) = paths.into_iter().nth(index).flatten() else {
            return;
        };
        let url = NSURL::fileURLWithPath(&NSString::from_str(&path.to_string_lossy()));
        if let Some(url) = url.absoluteString() {
            item.setString_forType(&url, r#type);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A pasteboard of its own for each test: tests run in parallel, and a
    /// pasteboard must not be used from two threads at once.
    fn private(test: &str) -> MacClipboard {
        MacClipboard::named(&format!(
            "cc.ctsite.inputweave.tests.{}.{test}",
            std::process::id()
        ))
    }

    #[test]
    fn writes_and_reads_back_every_format() {
        let mut board = private("formats");
        let content = ClipboardContent {
            items: vec![
                (ClipboardFormat::Text, "鍵鼠共享".as_bytes().to_vec()),
                (ClipboardFormat::Html, b"<b>hi</b>".to_vec()),
            ],
        };
        let before = board.change_count().unwrap();
        let after = board.write(&content).unwrap();
        assert!(after > before);
        assert_eq!(board.change_count().unwrap(), after);
        assert_eq!(board.read(1024).unwrap(), ClipboardRead::Content(content));
        assert!(matches!(board.read(4), Ok(ClipboardRead::TooLarge(_))));
    }

    #[test]
    fn concealed_content_is_not_read() {
        let board = private("concealed");
        board.pasteboard.clearContents();
        let concealed = NSString::from_str("org.nspasteboard.ConcealedType");
        let secret = NSData::with_bytes(b"hunter2");
        // SAFETY: reading an immutable framework constant.
        board
            .pasteboard
            .setData_forType(Some(&secret), unsafe { NSPasteboardTypeString });
        board
            .pasteboard
            .setData_forType(Some(&NSData::new()), &concealed);
        assert_eq!(board.read(1024).unwrap(), ClipboardRead::Sensitive);
    }
}
